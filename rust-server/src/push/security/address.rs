use std::net::{IpAddr, Ipv4Addr, Ipv6Addr};
fn in4(ip: Ipv4Addr, start: [u8; 4], mask: u32) -> bool {
    u32::from(ip) >> (32 - mask) == u32::from_be_bytes(start) >> (32 - mask)
}
fn in6(ip: Ipv6Addr, start: u128, mask: u32) -> bool {
    u128::from(ip) >> (128 - mask) == start >> (128 - mask)
}
pub fn public_address(ip: IpAddr) -> bool {
    match ip {
        IpAddr::V4(ip) => ![
            ([0, 0, 0, 0], 8),
            ([10, 0, 0, 0], 8),
            ([100, 64, 0, 0], 10),
            ([127, 0, 0, 0], 8),
            ([169, 254, 0, 0], 16),
            ([172, 16, 0, 0], 12),
            ([192, 0, 0, 0], 24),
            ([192, 0, 2, 0], 24),
            ([192, 88, 99, 0], 24),
            ([192, 168, 0, 0], 16),
            ([198, 18, 0, 0], 15),
            ([198, 51, 100, 0], 24),
            ([203, 0, 113, 0], 24),
            ([224, 0, 0, 0], 4),
            ([240, 0, 0, 0], 4),
        ]
        .iter()
        .any(|(start, mask)| in4(ip, *start, *mask)),
        IpAddr::V6(ip) => {
            in6(ip, 0x20000000000000000000000000000000, 3)
                && ![
                    (0x20010000000000000000000000000000, 32),
                    (0x20010010000000000000000000000000, 28),
                    (0x20010020000000000000000000000000, 28),
                    (0x20010db8000000000000000000000000, 32),
                    (0x20020000000000000000000000000000, 16),
                ]
                .iter()
                .any(|(start, mask)| in6(ip, *start, *mask))
        }
    }
}
